import Database from 'better-sqlite3';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
const __dirname=path.dirname(fileURLToPath(import.meta.url));
const dataDir=path.join(__dirname,'..','data');
fs.mkdirSync(dataDir,{recursive:true});
const db=new Database(path.join(dataDir,'memorymuse.db'));
db.pragma('journal_mode = WAL');
db.exec(`CREATE TABLE IF NOT EXISTS users(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT NOT NULL,email TEXT UNIQUE NOT NULL,mobile TEXT UNIQUE NOT NULL,password_hash TEXT NOT NULL,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS orders(id INTEGER PRIMARY KEY AUTOINCREMENT,order_id TEXT UNIQUE NOT NULL,user_id INTEGER NOT NULL,pages INTEGER NOT NULL,theme TEXT NOT NULL,magazine_price INTEGER NOT NULL,shipping INTEGER NOT NULL,total INTEGER NOT NULL,advance INTEGER NOT NULL,remaining INTEGER NOT NULL,status TEXT NOT NULL DEFAULT 'NEW',payment_status TEXT NOT NULL DEFAULT 'PENDING',created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id));`);
export default db;
